"""Local checks for the Jira playbook's published ADF examples."""

import json
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GUIDES = (
    ROOT / "cuahsi-project-setup" / "assets" / "issue-tracking-guidelines.md",
    ROOT / "docs" / "agents" / "issue-tracker.md",
)


class IssueTrackerGuidanceTests(unittest.TestCase):
    def examples(self, guide):
        return [json.loads(block) for block in re.findall(
            r"```json\n(.*?)\n```", guide.read_text(), re.DOTALL
        )]

    def assert_italic_prefix(self, paragraph, text):
        self.assertEqual(paragraph["type"], "paragraph")
        self.assertEqual(paragraph["content"], [
            {"type": "text", "text": text, "marks": [{"type": "em"}]}
        ])

    def test_generated_description_starts_with_italic_attribution(self):
        for guide in GUIDES:
            with self.subTest(guide=guide):
                document = self.examples(guide)[0]
                self.assertEqual(document["type"], "doc")
                self.assertEqual(document["version"], 1)
                self.assert_italic_prefix(
                    document["content"][0], "AI Generated by <Full Name>"
                )

    def test_revision_example_preserves_untouched_human_context(self):
        for guide in GUIDES:
            with self.subTest(guide=guide):
                document = self.examples(guide)[1]
                self.assertEqual(document["type"], "doc")
                self.assertEqual(document["version"], 1)
                self.assertEqual(document["content"][0], {
                    "type": "paragraph",
                    "content": [{"type": "text", "text": "Human-authored context, preserved unchanged."}],
                })
                self.assert_italic_prefix(
                    document["content"][1],
                    "AI revised (original text from <original author>); AI collaborator: <Full Name>",
                )
                self.assertEqual(document["content"][2]["type"], "paragraph")

    def test_comment_example_starts_with_one_italic_attribution(self):
        for guide in GUIDES:
            with self.subTest(guide=guide):
                document = self.examples(guide)[2]
                self.assertEqual(document["type"], "doc")
                self.assertEqual(document["version"], 1)
                self.assert_italic_prefix(
                    document["content"][0], "AI Generated by <Full Name>"
                )
                self.assertEqual(document["content"][1], {
                    "type": "paragraph",
                    "content": [{"type": "text", "text": "PR: <url>"}],
                })
                self.assertEqual(len(document["content"]), 2)

    def test_examples_have_valid_paragraph_heading_and_list_structure(self):
        children_by_type = {
            "doc": {"paragraph", "heading", "bulletList"},
            "paragraph": {"text"},
            "heading": {"text"},
            "bulletList": {"listItem"},
            "listItem": {"paragraph", "bulletList"},
        }
        for guide in GUIDES:
            for index, document in enumerate(self.examples(guide)):
                with self.subTest(guide=guide, example=index):
                    self.assertEqual(document["type"], "doc")
                    self.assertEqual(document["version"], 1)
                    pending = [document]
                    while pending:
                        node = pending.pop()
                        node_type = node["type"]
                        if node_type == "text":
                            self.assertIsInstance(node["text"], str)
                            self.assertTrue(node["text"])
                            for mark in node.get("marks", []):
                                self.assertEqual(mark, {"type": "em"})
                            continue
                        self.assertIn(node_type, children_by_type)
                        self.assertIsInstance(node["content"], list)
                        self.assertTrue(node["content"])
                        if node_type == "heading":
                            self.assertIn(node["attrs"]["level"], range(1, 7))
                        if node_type == "listItem":
                            self.assertEqual(node["content"][0]["type"], "paragraph")
                        for child in node["content"]:
                            self.assertIn(child["type"], children_by_type[node_type])
                        pending.extend(node["content"])

    def test_setup_template_renders_the_active_attribution_guidance(self):
        template = GUIDES[0].read_text()
        self.assertIn("## AI attribution\n", template)
        values = {
            "OBJECTIVE_KEY": "CAM-1616",
            "LABELS": "ProgramDev,AI",
            "LABEL_FILTER": 'labels = "ProgramDev" AND labels = "AI"',
            "BASE_BRANCH": "main",
            "GITHUB_REPO": "CUAHSI/ai-scaffolding",
        }
        for name, value in values.items():
            template = template.replace("{{" + name + "}}", value)
        self.assertEqual(template, GUIDES[1].read_text())


if __name__ == "__main__":
    unittest.main()
